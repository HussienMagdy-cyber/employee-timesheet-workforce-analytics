<?php
/**
 * Email delivery service for reports.
 *
 * @package ETWA
 */

declare(strict_types=1);

namespace ETWA\Services;

use ETWA\Helpers\BrandHelper;
use ETWA\Helpers\RoleManager;
use ETWA\Repositories\SettingsRepository;
use WP_Error;

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

final class EmailService {

	public function __construct(
		private ExportService $export = new ExportService(),
		private SettingsRepository $settings = new SettingsRepository(),
		private MailService $mail = new MailService(),
	) {}

	/**
	 * @return bool|WP_Error
	 */
	public function send_report( string $date_from, string $date_to, ?int $user_id = null, bool $force = false ): bool|WP_Error {
		if ( ! $force && ! current_user_can( RoleManager::CAP_EMAIL ) ) {
			return new WP_Error( 'forbidden', __( 'Cannot email reports.', 'etwa' ), array( 'status' => 403 ) );
		}

		$file = $this->export->generate( $date_from, $date_to, $user_id );
		if ( is_wp_error( $file ) ) {
			return $file;
		}

		$hr_email    = (string) $this->settings->get( 'hr_email', get_option( 'admin_email' ) );
		$owner_email = (string) $this->settings->get( 'owner_email', get_option( 'admin_email' ) );
		$cc_owner    = (bool) $this->settings->get( 'email_cc_owner', true );

		$subject = sprintf(
			/* translators: 1: start date, 2: end date */
			__( 'Workforce Timesheet Report: %1$s to %2$s', 'etwa' ),
			$date_from,
			$date_to
		);

		$content = sprintf(
			"%s\n\n%s",
			__( 'Please find the attached workforce analytics export.', 'etwa' ),
			sprintf(
				/* translators: %s: company / product name */
				__( 'Generated by %s.', 'etwa' ),
				BrandHelper::name()
			)
		);

		$headers = array();
		if ( $cc_owner && $owner_email && $owner_email !== $hr_email ) {
			$headers[] = 'Cc: ' . $owner_email;
		}

		$result = $this->mail->send(
			array(
				'to'          => $hr_email,
				'subject'     => $subject,
				'content'     => $content,
				'headers'     => $headers,
				'attachments' => array( $file ),
				'placeholders'=> array(
					'request_type' => __( 'Workforce Report', 'etwa' ),
				),
			)
		);

		if ( is_wp_error( $result ) ) {
			return $result;
		}

		return true;
	}
}
